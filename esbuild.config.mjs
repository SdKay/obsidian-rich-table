import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import { buildEntries, renderGenerated } from './changelog-gen.mjs';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';
const gen  = process.argv[2] === 'generate';

/** Parse `@theme-label-<lang>` comment headers (one per language; `en` is required)
 *  from CSS files and write src/themes/generated.ts so the renderer discovers
 *  themes automatically. */
function generateThemeMeta() {
	const themeDir = 'src/themes';
	if (!fs.existsSync(themeDir)) return;
	const files = fs.readdirSync(themeDir)
		.filter(f => f.endsWith('.css'))
		.sort();

	const themes = [];
	for (const file of files) {
		const css = fs.readFileSync(path.join(themeDir, file), 'utf8');
		const labels = {};
		for (const m of css.matchAll(/\/\*\s*@theme-label-([a-z]{2}):\s*(.+?)\s*\*\//g)) labels[m[1]] = m[2].trim();
		if (!labels.en) continue;
		themes.push({ id: file.replace('.css', ''), labels });
	}

	const rows = themes
		.map(t => `\t{ id: ${JSON.stringify(t.id)}, labels: ${JSON.stringify(t.labels)} },`)
		.join('\n');

	const out = `// Auto-generated by esbuild.config.mjs — do not edit directly.
// To add a theme: create src/themes/<id>.css with an @theme-label-en comment
// (and optionally @theme-label-<lang> for other languages).

export interface ThemeMeta {
\tid: string;
\t/** Label per language code; \`en\` is always present and is the fallback. */
\tlabels: { en: string } & Record<string, string | undefined>;
}

export const BUILTIN_THEMES: readonly ThemeMeta[] = [
${rows}
] as const;

export const BUILTIN_THEME_IDS = BUILTIN_THEMES.map(t => t.id);
`;
	fs.writeFileSync(path.join(themeDir, 'generated.ts'), out);
	console.log(`[themes] generated.ts updated (${themes.length} themes: ${themes.map(t => t.id).join(', ')})`);
}

/** Extract the `title:` field from a template YAML file's front matter
 *  (between the first two `---` lines) — used as that template's button
 *  label, so authoring a template's own (already-localized) title is the
 *  only metadata a new template needs, no separate label convention. */
function extractTemplateTitle(content, fallback) {
	const fm = content.match(/^---\n([\s\S]*?)\n---/);
	const body = fm ? fm[1] : content;
	const m = body.match(/^title:\s*(.+)$/m);
	if (!m) return fallback;
	return m[1].trim().replace(/^["']|["']$/g, '');
}

/** Scan src/templates/<id>-<lang>.yaml files and write src/templates/generated.ts —
 *  same auto-discovery shape as generateThemeMeta, plus the actual YAML content
 *  (templates are consumed as parsed data, so generated.ts embeds them as string
 *  imports). `<id>-en.yaml` is required and is the fallback; any other language is
 *  optional. To add a template: drop in `<id>-en.yaml` (and any translations), each
 *  with its own `title:` field — no other code changes needed. */
function generateTemplateMeta() {
	const dir = 'src/templates';
	if (!fs.existsSync(dir)) return;
	const files = fs.readdirSync(dir).filter(f => f.endsWith('.yaml'));

	const byId = new Map();
	for (const file of files) {
		const m = file.match(/^(.+)-([a-z]{2})\.yaml$/);
		if (!m) continue;
		if (!byId.has(m[1])) byId.set(m[1], []);
		byId.get(m[1]).push(m[2]);
	}

	const templates = [];
	for (const [id, langs] of byId) {
		if (!langs.includes('en')) {
			console.warn(`[templates] skipping "${id}" — needs ${id}-en.yaml`);
			continue;
		}
		const labels = {};
		for (const lang of langs.sort()) {
			labels[lang] = extractTemplateTitle(fs.readFileSync(path.join(dir, `${id}-${lang}.yaml`), 'utf8'), id);
		}
		templates.push({ id, langs: langs.sort(), labels });
	}

	// "demo" always sorts first (the default preview/first choice); everything
	// else alphabetical — keeps a stable, deliberate default without requiring
	// every future template to carry an explicit ordering field.
	templates.sort((a, b) => {
		if (a.id === 'demo') return -1;
		if (b.id === 'demo') return 1;
		return a.id.localeCompare(b.id);
	});

	const ident = (id, lang) => `${id.replace(/-/g, '_')}_${lang}`;
	const imports = templates
		.flatMap(t => t.langs.map(lang => `import ${ident(t.id, lang)} from './${t.id}-${lang}.yaml';`))
		.join('\n');
	const rows = templates
		.map(t => `\t{ id: ${JSON.stringify(t.id)}, labels: ${JSON.stringify(t.labels)}, content: { ${t.langs.map(lang => `${lang}: ${ident(t.id, lang)}`).join(', ')} } },`)
		.join('\n');

	const out = `// Auto-generated by esbuild.config.mjs — do not edit directly.
// To add a template: create src/templates/<id>-en.yaml (and optionally
// <id>-<lang>.yaml translations), each with a \`title:\` field in its YAML front
// matter (used as the button label).
${imports}

export interface TemplateMeta {
\tid: string;
\t/** Button label per language code; \`en\` is always present and is the fallback. */
\tlabels: { en: string } & Record<string, string | undefined>;
\t/** YAML source per language code; \`en\` is always present and is the fallback. */
\tcontent: { en: string } & Record<string, string | undefined>;
}

export const BUILTIN_TEMPLATES: readonly TemplateMeta[] = [
${rows}
] as const;
`;
	fs.writeFileSync(path.join(dir, 'generated.ts'), out);
	console.log(`[templates] generated.ts updated (${templates.length} templates: ${templates.map(t => t.id).join(', ')})`);
}

/** Regenerates src/changelog/generated.ts from git tags plus the version in
 *  package.json (see changelog-gen.mjs). Skips, keeping whatever is committed,
 *  when git history isn't usable — e.g. a shallow CI checkout with no tags. */
function generateChangelogMeta() {
	const outPath = 'src/changelog/generated.ts';
	let entries;
	try {
		const pendingVersion = JSON.parse(fs.readFileSync('package.json', 'utf8')).version;
		// The release commit inherits GIT_AUTHOR_DATE, so use it for the pending entry's date.
		const pendingDate = /^\d{4}-\d{2}-\d{2}/.exec(process.env.GIT_AUTHOR_DATE ?? '')?.[0];
		entries = buildEntries({ pendingVersion, pendingDate, warn: console.warn });
	} catch (err) {
		console.warn(`[changelog] skipping regeneration (${err.message}) — keeping existing generated.ts`);
		return;
	}
	fs.writeFileSync(outPath, renderGenerated(entries));
	console.log(`[changelog] generated.ts updated (${entries.length} versions, latest ${entries[0]?.version ?? 'n/a'})`);
}

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	loader: { '.yaml': 'text' },
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
});

/** Append all src/themes/*.css into styles.css after each build.
 *  Truncates any previously appended themes section first so repeated builds
 *  don't accumulate stale CSS rules that can't be overridden. */
function appendThemeCSS() {
	const themeDir = 'src/themes';
	if (!fs.existsSync(themeDir)) return;
	const files = fs.readdirSync(themeDir).filter(f => f.endsWith('.css')).sort();
	if (files.length === 0) return;
	const separator = '\n\n/* ── Built-in themes (auto-generated — do not edit below) ──── */\n';
	// Strip any previously appended themes block before re-appending.
	// CRLF normalized so the strip also works on a Windows (autocrlf) checkout.
	let base = fs.readFileSync('styles.css', 'utf8').replace(/\r\n/g, '\n');
	const cutIdx = base.indexOf(separator);
	if (cutIdx !== -1) base = base.slice(0, cutIdx);
	const themes = files.map(f => fs.readFileSync(path.join(themeDir, f), 'utf8').replace(/\r\n/g, '\n')).join('\n');
	fs.writeFileSync('styles.css', base + separator + themes);
}

if (gen) {
	generateThemeMeta();
	generateTemplateMeta();
	generateChangelogMeta();
	process.exit(0);
} else if (prod) {
	generateThemeMeta();
	generateTemplateMeta();
	generateChangelogMeta();
	await context.rebuild();
	appendThemeCSS();
	process.exit(0);
} else {
	generateThemeMeta();
	generateTemplateMeta();
	generateChangelogMeta();
	appendThemeCSS();
	await context.watch();
}

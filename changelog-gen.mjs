import { execFileSync } from 'node:child_process';

/** Runs a git subcommand and returns trimmed stdout; throws on any failure. */
export function git(args) {
	return execFileSync('git', args, { encoding: 'utf8' }).trim();
}

// First commit actually authored as this plugin (before it, the history is the
// sample-plugin template's own scaffolding). Bounds the oldest tag's range.
export const FORK_COMMIT = 'ea0c440';

const VERSION_TAG = /^\d+\.\d+\.\d+$/;

/**
 * The changelog entries, newest first. A tag only decides WHERE a release's
 * range ends; the release being prepared is described by `pendingVersion`
 * (package.json's version) even before its tag exists, so the generated file
 * is the same whether it is produced just before tagging or after.
 *
 * `read` is the git reader (injected for tests). `pendingVersion` is optional;
 * `pendingDate` (YYYY-MM-DD) is the release commit's date when the caller already
 * knows it (GIT_AUTHOR_DATE), else the latest commit's date.
 */
export function buildEntries({ read = git, pendingVersion, pendingDate, warn = () => {} } = {}) {
	const tags = read(['tag', '--list', '--sort=version:refname'])
		.split('\n').map(s => s.trim()).filter(t => VERSION_TAG.test(t));
	if (tags.length === 0) throw new Error('no version tags found');

	let firstRange = tags[0];
	try {
		read(['rev-parse', '--verify', `${FORK_COMMIT}^{commit}`]);
		firstRange = `${FORK_COMMIT}^..${tags[0]}`;
	} catch {
		warn(`[changelog] fork commit ${FORK_COMMIT} not reachable — the oldest tag's entry will include pre-fork template history`);
	}

	const titles = (range, version) => read(['log', '--format=%s', range])
		.split('\n').map(s => s.trim())
		.filter(s => s && s !== `chore: release ${version}`);

	const entries = tags.map((tag, i) => ({
		version: tag,
		date: read(['log', '-1', '--format=%ad', '--date=short', tag]),
		changes: titles(tags[i - 1] ? `${tags[i - 1]}..${tag}` : firstRange, tag),
	}));

	if (pendingVersion && VERSION_TAG.test(pendingVersion) && !tags.includes(pendingVersion)) {
		entries.push({
			version: pendingVersion,
			date: pendingDate ?? read(['log', '-1', '--format=%ad', '--date=short', 'HEAD']),
			changes: titles(`${tags[tags.length - 1]}..HEAD`, pendingVersion),
		});
	}
	return entries.reverse();
}

/** The text of src/changelog/generated.ts for the given entries. */
export function renderGenerated(entries) {
	const esc = s => JSON.stringify(s);
	const rows = entries.map(e => {
		const changeLines = e.changes.map(c => `\t\t${esc(c)},`).join('\n');
		return `\t{ version: ${esc(e.version)}, date: ${esc(e.date)}, changes: [\n${changeLines}\n\t] },`;
	}).join('\n');

	return `// Auto-generated by esbuild.config.mjs — do not edit directly.
// Rebuilt from git tags/commit history on every build (skipped, keeping this
// file as-is, when git history isn't available — e.g. a shallow CI checkout).

export interface ChangelogEntry {
\tversion: string;
\tdate: string;
\tchanges: string[];
}

export const CHANGELOG: readonly ChangelogEntry[] = [
${rows}
];
`;
}
